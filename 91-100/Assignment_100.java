package assignment_91_to_100;

public class Assignment_100 {

	public static void main(String[] args) {
	System.out.println("Write a Java program to demonstrate primitive type casting. 1)Widening 2)Narrowing");
	
	System.out.println("\n\nShowing Widening: \n");
	System.out.println("Converting int into double");
	int a = 15;
	double b = (double)a;
	System.out.println(b);
	
	
	System.out.println("\n\n\nShowing Narrowing: \n");
	System.out.println("Converting float into byte");
	float c = 2.65f;
	byte d = (byte) c;
	System.out.println(d);

	}

}
