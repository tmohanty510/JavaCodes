package assignment_51_to_60;

import java.util.Arrays;

public class Assignment_56 {

	public static void main(String[] args) {
		System.out.println("Write a program to declare, initialize, and print arrays of three data types (int, String and char) using the Arrays.toString() method\n\n");
		
		int a1 [] = {11,21,34,52};
		String a2[] = {"one", "two", "three", "four"};
		char a3 [] = {'a', 'b', 'c', 'd'};
		
		System.out.println("Array of int datatype: "+Arrays.toString(a1));
		System.out.println("Array of String datatype: "+Arrays.toString(a2));
		System.out.println("Array of char datatype: "+Arrays.toString(a3));

	}

}
